/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  MX_CAN2_Init();
  MX_SPI2_Init();
  MX_RTC_Init();
  MX_I2C1_Init();
  MX_USART2_UART_Init();
  MX_USB_OTG_FS_PCD_Init();
  /* USER CODE BEGIN 2 */


  if (ICM_Init(&icm_handle, &icm_hw) != HAL_OK)
  {
      Error_Handler();
  }

//  HAL_NVIC_DisableIRQ(EXTI0_IRQn);
  /* Giữ IMU đứng yên, phẳng trong lúc hiệu chỉnh */
  ICM_CalibrateGyro(&icm_handle, 200U);
  if (icm_handle.status.mag_available){
	  ICM_CalibrateMag(&icm_handle, 500U);
  }
//  icm_angle_last_tick = HAL_GetTick();
//  HAL_NVIC_EnableIRQ(EXTI0_IRQn);
//  (void)ICM_StartBurstRead(&icm_handle);
  icm_last_start_tick = HAL_GetTick();
  icm_angle_last_tick = icm_last_start_tick;

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	    ICM_CheckTimeout(&icm_handle);

	    if (icm_handle.status.state == ICM_STATE_ERROR)
	    {
	        ICM_ErrorRecovery(&icm_handle);
	    }

	    if (icm_handle.status.state == ICM_STATE_DATA_READY)
	    {
	        ICM_ProcessRaw(&icm_handle);

	        g_accel_x_g  = icm_handle.data.accel_g[0];
	        g_accel_y_g  = icm_handle.data.accel_g[1];
	        g_accel_z_g  = icm_handle.data.accel_g[2];
	        g_gyro_x_dps = icm_handle.data.gyro_dps[0];
	        g_gyro_y_dps = icm_handle.data.gyro_dps[1];
	        g_gyro_z_dps = icm_handle.data.gyro_dps[2];
	        g_mag_x_ut   = icm_handle.data.mag_ut[0];
	        g_mag_y_ut   = icm_handle.data.mag_ut[1];
	        g_mag_z_ut   = icm_handle.data.mag_ut[2];
	        g_temp_c     = icm_handle.data.temp_c;
	        g_icm_fault_flags = icm_handle.status.fault_flags;
	        g_mag_available = icm_handle.status.mag_available;
	        g_sample_count++;
	        {
	        	const float accel_roll_deg = atan2f(g_accel_y_g, g_accel_z_g) * (180.0f / (float)M_PI);
	            const float accel_pitch_deg = atan2f(-g_accel_x_g,
	                                                  sqrtf((g_accel_y_g * g_accel_y_g) + (g_accel_z_g * g_accel_z_g)))
	                                           * (180.0f / (float)M_PI);

	            const uint32_t now_tick = HAL_GetTick();
	            float dt_s = (float)(now_tick - icm_angle_last_tick) / 1000.0f;
	            icm_angle_last_tick = now_tick;
	            if ((dt_s <= 0.0f) || (dt_s > 0.5f))
	            {
	                /* Mau dau tien hoac gian doan bat thuong (vd sau debug
	                   halt lau) -> dung tam thoi 1/ODR de tranh nhay xung. */
	                dt_s = 0.01f;
	            }

	            const float gyro_roll_pred  = g_roll_deg  + (g_gyro_x_dps * dt_s);
	            const float gyro_pitch_pred = g_pitch_deg + (g_gyro_y_dps * dt_s);

	            g_roll_deg  = (ICM_COMPLEMENTARY_ALPHA * gyro_roll_pred)
	                        + ((1.0f - ICM_COMPLEMENTARY_ALPHA) * accel_roll_deg);
	            g_pitch_deg = (ICM_COMPLEMENTARY_ALPHA * gyro_pitch_pred)
	                        + ((1.0f - ICM_COMPLEMENTARY_ALPHA) * accel_pitch_deg);
	        }

	#if defined(ICM_UART_STREAM_ENABLE)
	        {
	            char line[96];
	            int len = snprintf(line, sizeof(line),
	            		 	 	 	 "%lu,%lu,%.4f,%.4f,%.4f,%.3f,%.3f,%.3f\r\n",
									 (unsigned long)HAL_GetTick(),
									 (unsigned long)g_sample_count,
									g_accel_x_g, g_accel_y_g, g_accel_z_g,
	                                g_gyro_x_dps, g_gyro_y_dps, g_gyro_z_dps);
	            if (len > 0)
	            {
	                (void)HAL_UART_Transmit(&huart2, (uint8_t *)line, (uint16_t)len, 10U);
	            }
	        }
	#endif
	    }

	    if ((HAL_GetTick() - icm_last_start_tick) >= ICM_SAMPLE_PERIOD_MS)
	    {
	        icm_last_start_tick = HAL_GetTick();
	        (void)ICM_StartBurstRead(&icm_handle);
	    }

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

  }
  /* USER CODE END 3 */
}

